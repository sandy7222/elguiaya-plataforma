-- =====================================================
-- Tabla de Configuración de Branding
-- =====================================================

-- Crear tabla de configuración de branding si no existe
CREATE TABLE IF NOT EXISTS public.branding_config (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    clave TEXT NOT NULL UNIQUE,
    valor TEXT,
    tipo_valor TEXT NOT NULL DEFAULT 'texto',
    descripcion TEXT,
    actualizado_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    actualizado_por UUID REFERENCES auth.users(id)
);

-- Añadir comentarios a la tabla
COMMENT ON TABLE public.branding_config IS 'Tabla de configuración de branding para personalización visual';
COMMENT ON COLUMN public.branding_config.clave IS 'Clave única de configuración (ej: bg_opacity, bg_brightness)';
COMMENT ON COLUMN public.branding_config.valor IS 'Valor de la configuración';
COMMENT ON COLUMN public.branding_config.tipo_valor IS 'Tipo de valor: texto, numero, color_hex, imagen_url, booleano';
COMMENT ON COLUMN public.branding_config.descripcion IS 'Descripción del propósito de la configuración';
COMMENT ON COLUMN public.branding_config.actualizado_at IS 'Fecha de última actualización';
COMMENT ON COLUMN public.branding_config.actualizado_por IS 'ID del usuario que realizó la última actualización';

-- Crear índices para mejor rendimiento
CREATE INDEX IF NOT EXISTS idx_branding_config_clave ON public.branding_config(clave);
CREATE INDEX IF NOT EXISTS idx_branding_config_tipo_valor ON public.branding_config(tipo_valor);
CREATE INDEX IF NOT EXISTS idx_branding_config_actualizado_at ON public.branding_config(actualizado_at);

-- Habilitar RLS (Row Level Security)
ALTER TABLE public.branding_config ENABLE ROW LEVEL SECURITY;

-- Políticas de seguridad
CREATE POLICY "Usuarios autenticados pueden ver configuración" ON public.branding_config
    FOR SELECT USING (auth.role() = 'authenticated');

CREATE POLICY "Usuarios autenticados pueden insertar configuración" ON public.branding_config
    FOR INSERT WITH CHECK (auth.role() = 'authenticated');

CREATE POLICY "Usuarios autenticados pueden actualizar configuración" ON public.branding_config
    FOR UPDATE USING (auth.role() = 'authenticated');

-- Permisos
GRANT SELECT, INSERT, UPDATE ON public.branding_config TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE branding_config_id_seq TO authenticated;

