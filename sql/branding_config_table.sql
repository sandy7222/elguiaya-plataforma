-- =====================================================
-- Funciones RPC para Branding
-- =====================================================

-- Función para obtener toda la configuración de branding
CREATE OR REPLACE FUNCTION public.obtener_branding_config()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    config_result jsonb;
BEGIN
    -- Construir objeto JSON con toda la configuración de branding
    SELECT jsonb_object_agg(clave, valor) INTO config_result
    FROM public.branding_config;
    
    RETURN COALESCE(config_result, '{}'::jsonb);
END;
$$;

-- Función para actualizar una configuración específica
CREATE OR REPLACE FUNCTION public.actualizar_branding_config(
    p_clave TEXT,
    p_valor TEXT,
    p_tipo_valor TEXT DEFAULT 'texto',
    p_descripcion TEXT DEFAULT NULL
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    user_id UUID;
BEGIN
    -- Obtener ID del usuario actual
    user_id := auth.uid();
    
    IF user_id IS NULL THEN
        RAISE EXCEPTION 'Usuario no autenticado';
    END IF;
    
    -- Insertar o actualizar configuración
    INSERT INTO public.branding_config (
        clave, 
        valor, 
        tipo_valor, 
        descripcion,
        actualizado_at,
        actualizado_por
    ) VALUES (
        p_clave,
        p_valor,
        p_tipo_valor,
        p_descripcion,
        NOW(),
        user_id
    )
    ON CONFLICT (clave)
    DO UPDATE SET
        valor = EXCLUDED.valor,
        tipo_valor = EXCLUDED.tipo_valor,
        descripcion = COALESCE(EXCLUDED.descripcion, branding_config.descripcion),
        actualizado_at = NOW(),
        actualizado_por = EXCLUDED.actualizado_por;
    
    RETURN true;
END;
$$;

-- Función para obtener configuración de login específica
CREATE OR REPLACE FUNCTION public.obtener_configuracion_login()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    config_result jsonb;
BEGIN
    -- Construir objeto JSON con configuración específica de login
    SELECT jsonb_build_object(
        'background_url', COALESCE(MAX(CASE WHEN clave = 'bg_url' THEN valor END), NULL),
        'opacity', COALESCE(MAX(CASE WHEN clave = 'bg_opacity' THEN valor END), '0.5')::float,
        'brightness', COALESCE(MAX(CASE WHEN clave = 'bg_brightness' THEN valor END), '1.0')::float,
        'logo_url', COALESCE(MAX(CASE WHEN clave = 'logo_url' THEN valor END), NULL),
        'favicon_url', COALESCE(MAX(CASE WHEN clave = 'favicon_url' THEN valor END), NULL),
        'color_primario', COALESCE(MAX(CASE WHEN clave = 'color_primario' THEN valor END), '#0D6EFD'),
        'color_secundario', COALESCE(MAX(CASE WHEN clave = 'color_secundario' THEN valor END), '#6C757D'),
        'color_acento', COALESCE(MAX(CASE WHEN clave = 'color_acento' THEN valor END), '#198754'),
        'font_family', COALESCE(MAX(CASE WHEN clave = 'font_family' THEN valor END), 'Roboto'),
        'enable_animations', COALESCE(MAX(CASE WHEN clave = 'enable_animations' THEN valor END), 'true')::boolean
    ) INTO config_result
    FROM public.branding_config
    WHERE clave IN (
        'bg_url', 'bg_opacity', 'bg_brightness',
        'logo_url', 'favicon_url', 'color_primario', 
        'color_secundario', 'color_acento', 'font_family',
        'enable_animations'
    );
    
    RETURN config_result;
END;
$$;

-- Permisos para funciones RPC
GRANT EXECUTE ON FUNCTION public.obtener_branding_config() TO authenticated;
GRANT EXECUTE ON FUNCTION public.actualizar_branding_config() TO authenticated;
GRANT EXECUTE ON FUNCTION public.obtener_configuracion_login() TO authenticated;

-- =====================================================
-- Vista para facilitar consultas
-- =====================================================

CREATE OR REPLACE VIEW public.vista_branding_config AS
SELECT 
    id,
    clave,
    valor,
    tipo_valor,
    descripcion,
    actualizado_at,
    actualizado_por
FROM public.branding_config
ORDER BY clave;

-- Permisos para la vista
GRANT SELECT ON public.vista_branding_config TO authenticated;
